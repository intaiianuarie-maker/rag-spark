"""Stage 12 — Gemma semantic citation verifier.

Evaluates whether each atomic claim in a candidate answer is supported by the
Stage-11-approved canonical evidence, **independently of the draft generation
call**. The Stage 11 pass (:mod:`answer.citation_integrity`) already proved
that every cited chunk *exists*, is *in-scope*, and carries *authentic* text —
Stage 12 asks a different, narrower question through an LLM:

    * Does the evidence actually *substantiate* the claim (supported)?
    * Is it only partly substantiated (partially_supported)?
    * Is the claim never mentioned (unsupported)?
    * Does the evidence say the *opposite* (contradicted)?
    * Can the relationship not be determined (uncertain)?

**Fail-closed.** Any verifier outage — timeout, upstream 429 exhaustion, model
refusal, or malformed JSON — is mapped to ``UNCERTAIN`` and
``abstain_recommended`` so a verified badge is **never** emitted when
verification could not complete.

**Bounded repair.** At most one narrowed recheck is attempted for
``partially_supported`` claims; the recheck result overrides the original only
when it moves to a more definitive verdict (``supported`` / ``unsupported`` /
``contradicted``).

**Publication gate.** Evaluates combined Stage 11 and Stage 12 results plus
pre-publication lifecycle revalidation to guard against concurrent deletions.
"""

