# ---------------------------------------------------------------------------
# Verdict & reason-code vocabulary
# ---------------------------------------------------------------------------


class Verdict(StrEnum):
    """Strict typed verdict per claim, as required by T-OR-06."""

    SUPPORTED = "supported"
    PARTIALLY_SUPPORTED = "partially_supported"
    UNSUPPORTED = "unsupported"
    CONTRADICTED = "contradicted"
    UNCERTAIN = "uncertain"


#: Reason codes the model may return (and adapter defaults when the model omits one).
REASON_SUPPORTED = "SUPPORTED"
REASON_PARTIAL_SUPPORT = "PARTIAL_SUPPORT"
REASON_NO_EVIDENCE = "NO_EVIDENCE"
REASON_CONTRADICTION_FOUND = "CONTRADICTION_FOUND"

#: Reason codes generated by the adapter on failure modes (fail-closed).
REASON_VERIFIER_OUTAGE = "VERIFIER_OUTAGE"
REASON_TIMEOUT = "TIMEOUT"
REASON_MODEL_REFUSED = "MODEL_REFUSED"
REASON_MALFORMED_JSON = "MALFORMED_JSON"
REASON_UNKNOWN_VERDICT = "UNKNOWN_VERDICT"
REASON_UPSTREAM_429_EXHAUSTED = "UPSTREAM_429_EXHAUSTED"


_DEFAULT_REASON: Mapping[Verdict, str] = {
    Verdict.SUPPORTED: REASON_SUPPORTED,
    Verdict.PARTIALLY_SUPPORTED: REASON_PARTIAL_SUPPORT,
    Verdict.UNSUPPORTED: REASON_NO_EVIDENCE,
    Verdict.CONTRADICTED: REASON_CONTRADICTION_FOUND,
    Verdict.UNCERTAIN: REASON_VERIFIER_OUTAGE,
}


# ---------------------------------------------------------------------------
# Data models
# ---------------------------------------------------------------------------


class CanonicalEvidence(BaseModel):
    """A single piece of Stage-11-approved canonical evidence for a claim.

    Built from :class:`~answer.models.Citation` records that survived the
    deterministic integrity pass — i.e. the chunk exists, is in-scope, is the
    current document version, and carries the authoritative passage text.
    """

    evidence_id: str
    content: str
    filename: str | None = None
    page: int | None = None
    section: str | None = None
    document_id: str | None = None


class SupportSpan(BaseModel):
    """Verbatim text span within an evidence passage substantiating a claim."""

    evidence_id: str
    start: int = 0
    end: int = 0


class ClaimVerdict(BaseModel):
    """Typed verdict for one claim against its evidence.

    Schema per claim (T-OR-06):
      ``claim_id``, ``verdict``, ``evidence_ids``, ``support_spans``,
      ``contradictions``, ``reason_code``.
    """

    claim_id: str
    verdict: Verdict
    evidence_ids: list[str] = Field(default_factory=list)
    support_spans: list[SupportSpan] = Field(default_factory=list)
    contradictions: list[str] = Field(default_factory=list)
    reason_code: str | None = None


class SemanticVerificationReport(BaseModel):
    """Aggregated result of a semantic verification pass over all claims.

    * ``all_supported`` — every claim verdict is ``supported``.
    * ``claim_verdicts`` — per-claim typed verdicts.
    * ``abstain_recommended`` — ``True`` when any claim is
      ``unsupported``, ``contradicted`` **or** ``uncertain`` (fail-closed),
      signalling the caller must not emit a verified badge.
    * ``contradictions`` — aggregated contradiction spans to surface to the
      user / disclosure layer.
    """

    all_supported: bool
    claim_verdicts: list[ClaimVerdict] = Field(default_factory=list)
    abstain_recommended: bool = False
    contradictions: list[str] = Field(default_factory=list)


class PublicationStatus(StrEnum):
    """Publication gate decision status (T-OR-06)."""

    VERIFIED = "verified"
    NEEDS_REVIEW = "needs_review"
    ABSTAIN = "abstain"
    REJECTED = "rejected"


class PublicationGateResult(BaseModel):
    """Final publication gate evaluation combining Stage 11 and Stage 12 (T-OR-06).

    Ensures no unverified draft tokens or corrupted citations reach the user.
    """

    can_publish: bool
    status: PublicationStatus
    stage11_valid: bool
    stage12_valid: bool
    verifier_model: str = ""
    reasons: list[str] = Field(default_factory=list)
    disclosures: list[str] = Field(default_factory=list)
    limitations: list[str] = Field(default_factory=list)


class SemanticVerificationError(RuntimeError):
    """Raised when the verification pass itself cannot start."""


