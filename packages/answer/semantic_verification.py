# ---------------------------------------------------------------------------
# Orchestration
# ---------------------------------------------------------------------------


def _evidence_from_citations(
    citations: Sequence[Citation],
) -> dict[str, CanonicalEvidence]:
    """Build an evidence map keyed by chunk_id from accepted citations."""
    evidence: dict[str, CanonicalEvidence] = {}
    for citation in citations:
        if citation.content:  # only hydrated citations carry canonical text
            evidence[citation.chunk_id] = CanonicalEvidence(
                evidence_id=citation.chunk_id,
                content=citation.content,
                filename=citation.filename,
                page=citation.page,
                section=citation.section,
                document_id=citation.document_id,
            )
    return evidence


def _resolve_evidence(
    claim: Claim,
    evidence_map: Mapping[str, CanonicalEvidence],
) -> list[CanonicalEvidence]:
    """Resolve the canonical evidence for one claim's cited chunk_ids."""
    return [evidence_map[cid] for cid in claim.chunk_ids if cid in evidence_map]


def _uncertain_verdict(
    claim_id: str,
    evidence_ids: list[str],
    reason_code: str,
) -> ClaimVerdict:
    """Build a fail-closed UNCERTAIN verdict (never emits a verified badge)."""
    return ClaimVerdict(
        claim_id=claim_id,
        verdict=Verdict.UNCERTAIN,
        evidence_ids=evidence_ids,
        reason_code=reason_code,
    )


def default_reason(verdict: Verdict) -> str:
    """Return the default reason code for a verdict."""
    return _DEFAULT_REASON.get(verdict, "UNKNOWN")


async def verify_semantic_claims(
    claims: Sequence[Claim],
    integrity_report: CitationIntegrityReport,
    verifier: SemanticClaimVerifier,
) -> SemanticVerificationReport:
    """Verify each claim against Stage-11-approved canonical evidence.

    Takes the candidate answer's atomic draft claims together with the
    :class:`CitationIntegrityReport` that Stage 11 produced, resolves which
    accepted citations back each claim, and asks *verifier* to evaluate the
    semantic relationship per claim.

    Fail-closed (T-OR-06):
      * The verifier is called inside a per-claim ``try/except``. Any
        exception — timeout, transport error, unexpected crash — maps to an
        ``UNCERTAIN`` verdict with ``abstain_recommended=True``.
      * Claims whose cited chunk_ids did not survive Stage 11 (or whose
        evidence content is missing) are ``UNSUPPORTED`` without a model call.

    Bounded repair (T-OR-06):
      * When a claim is ``partially_supported`` the orchestrator attempts
        **at most one** narrowed recheck (``recheck=True``). The recheck
        result replaces the original only when it is more definitive — moving
        to ``supported``, ``unsupported``, or ``contradicted``. A
        ``partially_supported`` or ``uncertain`` recheck — or a recheck that
        raises — keeps the original verdict.
    """
    evidence_map = _evidence_from_citations(integrity_report.accepted_citations)

    verdicts: list[ClaimVerdict] = []
    all_contradictions: list[str] = []

    for claim in claims:
        claim_id = claim.text or "<unnamed-claim>"
        evidence = _resolve_evidence(claim, evidence_map)
        evidence_ids = [e.evidence_id for e in evidence]

        # No surviving evidence -> the claim cannot be substantiated.
        if not evidence:
            verdict = ClaimVerdict(
                claim_id=claim_id,
                verdict=Verdict.UNSUPPORTED,
                evidence_ids=list(claim.chunk_ids),
                reason_code=REASON_NO_EVIDENCE,
            )
        else:
            try:
                verdict = await verifier.verify_claim(claim.text, evidence)
            except TimeoutError:
                logger.warning(
                    "semantic_verification_timeout",
                    extra={"claim_id": claim_id},
                )
                verdict = _uncertain_verdict(
                    claim_id, evidence_ids, REASON_TIMEOUT
                )
            except Exception:
                logger.exception(
                    "semantic_verification_outage",
                    extra={"claim_id": claim_id},
                )
                verdict = _uncertain_verdict(
                    claim_id, evidence_ids, REASON_VERIFIER_OUTAGE
                )
            else:
                # Bounded repair: at most one narrowed recheck for partial.
                if verdict.verdict == Verdict.PARTIALLY_SUPPORTED:
                    verdict = await _bounded_recheck(
                        verifier, claim.text, evidence, verdict
                    )

        if verdict.verdict == Verdict.CONTRADICTED:
            all_contradictions.extend(verdict.contradictions)

        verdicts.append(verdict)

    has_negative = any(
        v.verdict
        in (
            Verdict.UNSUPPORTED,
            Verdict.CONTRADICTED,
            Verdict.UNCERTAIN,
            Verdict.PARTIALLY_SUPPORTED,
        )
        for v in verdicts
    )

    return SemanticVerificationReport(
        all_supported=all(v.verdict == Verdict.SUPPORTED for v in verdicts),
        claim_verdicts=verdicts,
        abstain_recommended=has_negative,
        contradictions=all_contradictions,
    )


async def _bounded_recheck(
    verifier: SemanticClaimVerifier,
    claim_text: str,
    evidence: list[CanonicalEvidence],
    original: ClaimVerdict,
) -> ClaimVerdict:
    """Attempt at most one narrowed recheck for a ``partially_supported`` claim.

    Returns the recheck verdict only when it is *more definitive* than the
    original (i.e. moves to ``supported`` / ``unsupported`` / ``contradicted``).
    A ``partially_supported`` or ``uncertain`` recheck — or a recheck that
    raises — keeps the original verdict.
    """
    try:
        recheck = await verifier.verify_claim(
            claim_text, evidence, recheck=True
        )
    except Exception:
        logger.debug(
            "semantic_verification_recheck_failed",
            extra={"claim_id": original.claim_id},
        )
        return original

    if recheck.verdict in (
        Verdict.SUPPORTED,
        Verdict.UNSUPPORTED,
        Verdict.CONTRADICTED,
    ):
        return recheck

    # partially_supported or uncertain recheck -> keep original
    return original


# ---------------------------------------------------------------------------
# Final publication gate (T-OR-06)
# ---------------------------------------------------------------------------


async def evaluate_publication_gate(
    claims: Sequence[Claim],
    integrity_report: CitationIntegrityReport,
    semantic_report: SemanticVerificationReport,
    *,
    chunk_lookup: ChunkLookup | None = None,
    verifier_model: str = "google/gemma-4-26b-a4b-it",
) -> PublicationGateResult:
    """Evaluate whether a grounded answer may be published to the user.

    Combines:
    1. Stage 11 structural citation integrity (existence, bounds, text fidelity).
    2. Stage 12 semantic claim verification (Gemma free -> paid).
    3. Final pre-publication lifecycle check: ensures cited documents were not
       deleted or superseded between initial retrieval and final output.
    """
    reasons: list[str] = []
    disclosures: list[str] = list(integrity_report.omissions)
    limitations: list[str] = []

    # 1. Structural integrity check (Stage 11)
    stage11_ok = integrity_report.valid
    if not stage11_ok:
        for rej in integrity_report.rejected_citations:
            reasons.append(f"STAGE_11_REJECTED_{rej.reason.value}: {rej.citation.chunk_id}")

    # 2. Semantic verification check (Stage 12)
    stage12_ok = semantic_report.all_supported and not semantic_report.abstain_recommended
    if not stage12_ok:
        for cv in semantic_report.claim_verdicts:
            if cv.verdict != Verdict.SUPPORTED:
                reasons.append(f"STAGE_12_{cv.verdict.value.upper()}: {cv.claim_id[:40]}")

    if semantic_report.contradictions:
        disclosures.extend(semantic_report.contradictions)

    # 3. Pre-publication lifecycle revalidation
    lifecycle_ok = True
    if chunk_lookup is not None and integrity_report.accepted_citations:
        chunk_ids = [c.chunk_id for c in integrity_report.accepted_citations]
        try:
            live = await chunk_lookup.get_many(chunk_ids)
            missing = [cid for cid in chunk_ids if cid not in live]
            if missing:
                lifecycle_ok = False
                reasons.append(f"DOCUMENT_MUTATED_OR_DELETED_DURING_VERIFICATION: {missing}")
        except Exception as exc:
            lifecycle_ok = False
            reasons.append(f"LIFECYCLE_RECHECK_ERROR: {exc}")

    # Decision synthesis (Fail-closed)
    if not stage11_ok or not lifecycle_ok:
        status = PublicationStatus.REJECTED
        can_publish = False
    elif any(cv.verdict == Verdict.CONTRADICTED for cv in semantic_report.claim_verdicts):
        status = PublicationStatus.ABSTAIN
        can_publish = False
    elif any(cv.verdict == Verdict.UNCERTAIN for cv in semantic_report.claim_verdicts):
        status = PublicationStatus.NEEDS_REVIEW
        can_publish = False
    elif any(cv.verdict == Verdict.UNSUPPORTED for cv in semantic_report.claim_verdicts):
        status = PublicationStatus.ABSTAIN
        can_publish = False
    elif any(cv.verdict == Verdict.PARTIALLY_SUPPORTED for cv in semantic_report.claim_verdicts):
        status = PublicationStatus.NEEDS_REVIEW
        can_publish = False
    elif stage11_ok and stage12_ok and lifecycle_ok:
        status = PublicationStatus.VERIFIED
        can_publish = True
    else:
        status = PublicationStatus.NEEDS_REVIEW
        can_publish = False

    return PublicationGateResult(
        can_publish=can_publish,
        status=status,
        stage11_valid=stage11_ok,
        stage12_valid=stage12_ok,
        verifier_model=verifier_model,
        reasons=reasons,
        disclosures=disclosures,
        limitations=limitations,
    )
